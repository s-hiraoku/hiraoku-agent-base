import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";
const root = new URL("./", import.meta.url);
const files = [
  "../../../src/agent-notify/display-projection.ts",
  "controller.ts",
  "plugin-source.ts",
];
const source = files
  .map((file) => readFileSync(new URL(file, root), "utf8"))
  .join("\n");
const result = ts.transpileModule(source, {
  compilerOptions: {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ES2022,
  },
  transformers: {
    before: [
      (context) => (tree) =>
        ts.visitEachChild(
          tree,
          (node) => {
            if (ts.isImportDeclaration(node)) {
              const name = node.moduleSpecifier.text;
              if (name.startsWith(".")) return undefined;
              if (!["@hermes/plugin-sdk", "react"].includes(name))
                throw new Error("Unsupported runtime import");
            }
            return node;
          },
          context,
        ),
    ],
  },
});
const output =
  "// Generated by desktop/build.mjs; source and tests are shipped alongside.\n" +
  result.outputText;
const target = new URL("plugin.js", root);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output)
    throw new Error("Generated desktop/plugin.js is stale");
} else writeFileSync(target, output);
